BEGIN;

-- Fail quickly instead of waiting behind a busy production writer. This setting
-- is local to this migration transaction and is restored automatically.
SET LOCAL lock_timeout = '5s';

-- This index may already exist because of an out-of-band schema change. Reuse
-- it only when its complete catalog definition is exactly the one expected by
-- the Prisma schema. A same-named invalid or different index is a hard failure.
DO $migration$
DECLARE
  expected_definition CONSTANT TEXT :=
    'CREATE UNIQUE INDEX "StoredFile_sourceProvider_sourceAttachmentId_key" ON public."StoredFile" USING btree ("sourceProvider", "sourceAttachmentId")';
  index_oid OID := to_regclass('public."StoredFile_sourceProvider_sourceAttachmentId_key"');
  actual_definition TEXT;
  is_unique BOOLEAN;
  is_valid BOOLEAN;
  is_ready BOOLEAN;
BEGIN
  IF index_oid IS NULL THEN
    EXECUTE
      'CREATE UNIQUE INDEX "StoredFile_sourceProvider_sourceAttachmentId_key" ' ||
      'ON "StoredFile"("sourceProvider", "sourceAttachmentId")';
  ELSE
    SELECT pg_get_indexdef(index_relation.indexrelid),
           index_relation.indisunique,
           index_relation.indisvalid,
           index_relation.indisready
      INTO actual_definition, is_unique, is_valid, is_ready
      FROM pg_index index_relation
      WHERE index_relation.indexrelid = index_oid;

    IF actual_definition IS NULL
       OR actual_definition <> expected_definition
       OR is_unique IS DISTINCT FROM true
       OR is_valid IS DISTINCT FROM true
       OR is_ready IS DISTINCT FROM true THEN
      RAISE EXCEPTION USING
        ERRCODE = '55000',
        MESSAGE = 'StoredFile_sourceProvider_sourceAttachmentId_key has an unexpected definition',
        DETAIL = format(
          'Expected: %s; actual: %s; unique=%s; valid=%s; ready=%s',
          expected_definition,
          COALESCE(actual_definition, '<not an index>'),
          COALESCE(is_unique::TEXT, '<unknown>'),
          COALESCE(is_valid::TEXT, '<unknown>'),
          COALESCE(is_ready::TEXT, '<unknown>')
        ),
        HINT = 'Stop the migration and inspect the existing production index; do not mark the migration as applied.';
    END IF;
  END IF;
END
$migration$;

-- Deliberately not guarded with IF NOT EXISTS. CaseAsset is new in this
-- migration; any pre-existing table or same-named index is conflicting partial
-- state that must be inspected rather than silently accepted.
CREATE TABLE "CaseAsset" (
  "id" TEXT NOT NULL,
  "storedFileId" TEXT NOT NULL,
  "sourceRecordId" TEXT NOT NULL,
  "sourceFieldId" TEXT NOT NULL,
  "sourceEntityType" "CommunicationSourceEntityType" NOT NULL,
  "sourceHospitalRecordId" TEXT NOT NULL,
  "role" "CommunicationAssetRole" NOT NULL,
  "displayOrder" INTEGER NOT NULL,
  "active" BOOLEAN NOT NULL DEFAULT true,
  "firstSeenAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "lastSeenAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "removedAt" TIMESTAMP(3),
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "CaseAsset_pkey" PRIMARY KEY ("id")
);

-- These are the exact 63-byte names generated by the current Prisma version.
CREATE UNIQUE INDEX "CaseAsset_sourceEntityType_sourceRecordId_sourceFieldId_sto_key"
ON "CaseAsset"("sourceEntityType", "sourceRecordId", "sourceFieldId", "storedFileId");
CREATE INDEX "CaseAsset_sourceHospitalRecordId_sourceEntityType_sourceRec_idx"
ON "CaseAsset"("sourceHospitalRecordId", "sourceEntityType", "sourceRecordId", "active");
CREATE INDEX "CaseAsset_storedFileId_active_idx" ON "CaseAsset"("storedFileId", "active");
ALTER TABLE "CaseAsset" ADD CONSTRAINT "CaseAsset_storedFileId_fkey"
FOREIGN KEY ("storedFileId") REFERENCES "StoredFile"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- Preserve every distinct already-processed portal asset without inventing a
-- delivery. The id tie-breaker makes DISTINCT ON deterministic when two
-- CommunicationAsset rows have the same creation timestamp.
INSERT INTO "CaseAsset" (
  "id", "storedFileId", "sourceRecordId", "sourceFieldId", "sourceEntityType",
  "sourceHospitalRecordId", "role", "displayOrder", "active", "firstSeenAt",
  "lastSeenAt", "createdAt", "updatedAt"
)
SELECT DISTINCT ON (
  stored_file."sourceEntityType", stored_file."sourceRecordId",
  stored_file."sourceFieldId", stored_file.id
)
  'legacy_' || md5(
    stored_file."sourceEntityType"::text || ':' || stored_file."sourceRecordId" || ':' ||
    stored_file."sourceFieldId" || ':' || stored_file.id
  ),
  stored_file.id,
  stored_file."sourceRecordId",
  stored_file."sourceFieldId",
  stored_file."sourceEntityType",
  stored_file."sourceHospitalRecordId",
  communication_asset.role,
  communication_asset."displayOrder",
  true,
  communication_asset."createdAt",
  CURRENT_TIMESTAMP,
  communication_asset."createdAt",
  CURRENT_TIMESTAMP
FROM "CommunicationAsset" communication_asset
JOIN "StoredFile" stored_file ON stored_file.id = communication_asset."storedFileId"
WHERE stored_file."sourceEntityType" IN ('SERVICE_ORDER', 'INSPECTION')
ORDER BY stored_file."sourceEntityType", stored_file."sourceRecordId",
  stored_file."sourceFieldId", stored_file.id,
  communication_asset."createdAt" ASC, communication_asset.id ASC;

-- Executable SQL postconditions. Any failed assertion aborts and rolls back the
-- complete migration, including a newly created StoredFile index.
DO $migration$
DECLARE
  expected_count BIGINT;
  actual_count BIGINT;
  mismatch_count BIGINT;
BEGIN
  IF pg_get_indexdef(to_regclass(
       'public."CaseAsset_sourceEntityType_sourceRecordId_sourceFieldId_sto_key"'
     )) IS DISTINCT FROM
     'CREATE UNIQUE INDEX "CaseAsset_sourceEntityType_sourceRecordId_sourceFieldId_sto_key" ON public."CaseAsset" USING btree ("sourceEntityType", "sourceRecordId", "sourceFieldId", "storedFileId")' THEN
    RAISE EXCEPTION 'CaseAsset logical uniqueness index failed its postcondition';
  END IF;

  IF pg_get_indexdef(to_regclass(
       'public."CaseAsset_sourceHospitalRecordId_sourceEntityType_sourceRec_idx"'
     )) IS DISTINCT FROM
     'CREATE INDEX "CaseAsset_sourceHospitalRecordId_sourceEntityType_sourceRec_idx" ON public."CaseAsset" USING btree ("sourceHospitalRecordId", "sourceEntityType", "sourceRecordId", active)' THEN
    RAISE EXCEPTION 'CaseAsset hospital scope index failed its postcondition';
  END IF;

  IF pg_get_indexdef(to_regclass(
       'public."CaseAsset_storedFileId_active_idx"'
     )) IS DISTINCT FROM
     'CREATE INDEX "CaseAsset_storedFileId_active_idx" ON public."CaseAsset" USING btree ("storedFileId", active)' THEN
    RAISE EXCEPTION 'CaseAsset stored file index failed its postcondition';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint constraint_definition
    WHERE constraint_definition.conname = 'CaseAsset_storedFileId_fkey'
      AND constraint_definition.conrelid = 'public."CaseAsset"'::regclass
      AND constraint_definition.confrelid = 'public."StoredFile"'::regclass
      AND constraint_definition.contype = 'f'
      AND constraint_definition.confdeltype = 'r'
      AND constraint_definition.confupdtype = 'c'
  ) THEN
    RAISE EXCEPTION 'CaseAsset storedFileId foreign key failed its postcondition';
  END IF;

  WITH expected AS (
    SELECT DISTINCT ON (
      stored_file."sourceEntityType", stored_file."sourceRecordId",
      stored_file."sourceFieldId", stored_file.id
    )
      'legacy_' || md5(
        stored_file."sourceEntityType"::text || ':' || stored_file."sourceRecordId" || ':' ||
        stored_file."sourceFieldId" || ':' || stored_file.id
      ) AS id,
      stored_file.id AS "storedFileId",
      stored_file."sourceRecordId",
      stored_file."sourceFieldId",
      stored_file."sourceEntityType",
      stored_file."sourceHospitalRecordId",
      communication_asset.role,
      communication_asset."displayOrder",
      communication_asset."createdAt" AS "firstSeenAt",
      communication_asset."createdAt" AS "createdAt"
    FROM "CommunicationAsset" communication_asset
    JOIN "StoredFile" stored_file ON stored_file.id = communication_asset."storedFileId"
    WHERE stored_file."sourceEntityType" IN ('SERVICE_ORDER', 'INSPECTION')
    ORDER BY stored_file."sourceEntityType", stored_file."sourceRecordId",
      stored_file."sourceFieldId", stored_file.id,
      communication_asset."createdAt" ASC, communication_asset.id ASC
  ), mismatches AS (
    SELECT expected.id
    FROM expected
    LEFT JOIN "CaseAsset" case_asset ON case_asset.id = expected.id
    WHERE case_asset.id IS NULL
       OR case_asset."storedFileId" IS DISTINCT FROM expected."storedFileId"
       OR case_asset."sourceRecordId" IS DISTINCT FROM expected."sourceRecordId"
       OR case_asset."sourceFieldId" IS DISTINCT FROM expected."sourceFieldId"
       OR case_asset."sourceEntityType" IS DISTINCT FROM expected."sourceEntityType"
       OR case_asset."sourceHospitalRecordId" IS DISTINCT FROM expected."sourceHospitalRecordId"
       OR case_asset.role IS DISTINCT FROM expected.role
       OR case_asset."displayOrder" IS DISTINCT FROM expected."displayOrder"
       OR case_asset.active IS DISTINCT FROM true
       OR case_asset."firstSeenAt" IS DISTINCT FROM expected."firstSeenAt"
       OR case_asset."createdAt" IS DISTINCT FROM expected."createdAt"
  )
  SELECT
    (SELECT count(*) FROM expected),
    (SELECT count(*) FROM "CaseAsset"),
    (SELECT count(*) FROM mismatches)
  INTO expected_count, actual_count, mismatch_count;

  IF actual_count <> expected_count OR mismatch_count <> 0 THEN
    RAISE EXCEPTION USING
      MESSAGE = 'CommunicationAsset to CaseAsset backfill failed its postcondition',
      DETAIL = format(
        'expected rows=%s; actual rows=%s; mismatched or missing rows=%s',
        expected_count, actual_count, mismatch_count
      );
  END IF;

  IF EXISTS (
    SELECT 1
    FROM "CaseAsset" case_asset
    JOIN "StoredFile" stored_file ON stored_file.id = case_asset."storedFileId"
    WHERE case_asset."sourceHospitalRecordId" IS DISTINCT FROM stored_file."sourceHospitalRecordId"
  ) THEN
    RAISE EXCEPTION 'CaseAsset hospital scope differs from its StoredFile after backfill';
  END IF;
END
$migration$;

COMMIT;
